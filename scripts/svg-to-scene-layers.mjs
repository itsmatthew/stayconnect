// Generates src/components/home/scenery/scene-layers.tsx from public/home-background.svg.
// Usage: node scripts/svg-to-scene-layers.mjs
// Each layer is a run of the SVG's top-level children; ids are prefixed per instance via `ids`.
import fs from "node:fs";

const SRC = "public/home-background.svg";
const OUT = "src/components/home/scenery/scene-layers.tsx";

// Top-level child index ranges (inclusive) per layer, in paint order.
const LAYERS = {
  Defs: [0, 0],
  Sky: [1, 1],
  Clouds: [2, 2],
  Sun: [3, 4],
  Ridges: [5, 6],
  Town: [7, 7],
  Ground: [8, 10],
  Fog: [11, 11],
  Hills: [12, 18],
  River: [19, 21],
  LittleTrees: [22, 37],
  Flowers: [38, 55],
};

// Single-node layers whose children are also exported on their own (the wide scene places them separately).
// The layer itself still renders the original wrapper around them, so the phone scene is unchanged.
const SPLIT = {
  Clouds: ["Cloud1", "Cloud2", "Cloud3"],
  Town: ["Church", "Houses"],
};

const svg = fs.readFileSync(SRC, "utf8").replace(/<metadata>[\s\S]*?<\/metadata>/, "");
const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));

// Parse into a tree.
function parse(src) {
  const root = { children: [] };
  const stack = [root];
  const re = /<(\/?)([a-zA-Z][\w:-]*)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g;
  let m;
  let last = 0;
  while ((m = re.exec(src))) {
    if (src.slice(last, m.index).trim()) throw new Error(`Unexpected text near ${m.index}`);
    last = re.lastIndex;
    const [, close, tag, rawAttrs, self] = m;
    if (close) {
      stack.pop();
      continue;
    }
    const attrs = [...rawAttrs.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]);
    const node = { tag, attrs, children: [] };
    stack.at(-1).children.push(node);
    if (!self) stack.push(node);
  }
  return root.children;
}

const nodes = parse(body);
const ids = new Set();
(function collect(list) {
  for (const n of list) {
    for (const [k, v] of n.attrs) if (k === "id") ids.add(v);
    collect(n.children);
  }
})(nodes);

const camel = (k) => (k === "class" ? "className" : k.replace(/[-:]([a-z])/g, (_, c) => c.toUpperCase()));
const key = (v) => v.replace(/[^\w]/g, "_");

function attr([k, v]) {
  if (k === "id") return `id={ids.${key(v)}}`;
  if (k === "style") {
    const obj = Object.fromEntries(
      v.split(";").filter((s) => s.trim()).map((decl) => {
        const i = decl.indexOf(":");
        return [camel(decl.slice(0, i).trim()), decl.slice(i + 1).trim()];
      }),
    );
    return `style={${JSON.stringify(obj)}}`;
  }
  const name = k.startsWith("aria-") || k.startsWith("data-") ? k : camel(k);
  if (/url\(#/.test(v)) {
    const tpl = v.replace(/url\(#([^)]+)\)/g, (_, id) => `url(#\${ids.${key(id)}})`);
    return `${name}={\`${tpl}\`}`;
  }
  return `${name}=${JSON.stringify(v)}`;
}

function jsx(n, indent) {
  const pad = "  ".repeat(indent);
  const open = `<${n.tag}${n.attrs.length ? " " + n.attrs.map(attr).join(" ") : ""}`;
  if (!n.children.length) return `${pad}${open} />`;
  return `${pad}${open}>\n${n.children.map((c) => jsx(c, indent + 1)).join("\n")}\n${pad}</${n.tag}>`;
}

const idKeys = [...ids].map(key);
let out = `// GENERATED by scripts/svg-to-scene-layers.mjs from public/home-background.svg. Do not edit by hand.
/* eslint-disable */

export const SCENE_ID_NAMES = ${JSON.stringify(idKeys)} as const;
export type SceneIds = Record<(typeof SCENE_ID_NAMES)[number], string>;
type LayerProps = { ids: SceneIds };
`;
const component = (name, body) =>
  `\nexport function ${name}({ ids }: LayerProps) {\n  return (\n    <>\n${body}\n    </>\n  );\n}\n`;
for (const [name, [from, to]] of Object.entries(LAYERS)) {
  const part = nodes.slice(from, to + 1);
  const split = SPLIT[name];
  if (!split) {
    out += component(name, part.map((n) => jsx(n, 3)).join("\n"));
    continue;
  }
  const [wrapper] = part;
  if (part.length !== 1 || wrapper.children.length !== split.length) throw new Error(`Can't split ${name}`);
  wrapper.children.forEach((child, i) => (out += component(split[i], jsx(child, 3))));
  const open = jsx({ ...wrapper, children: [] }, 3).replace(/ \/>$/, ">");
  const kids = split.map((c) => `        <${c} ids={ids} />`).join("\n");
  out += component(name, `${open}\n${kids}\n      </${wrapper.tag}>`);
}
const covered = Object.values(LAYERS).reduce((a, [f, t]) => a + (t - f + 1), 0);
if (covered !== nodes.length) throw new Error(`Layers cover ${covered} of ${nodes.length} top-level nodes`);
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${nodes.length} nodes, ${idKeys.length} ids`);
